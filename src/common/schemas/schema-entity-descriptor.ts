import type { EntityDescriptorModelType, FieldConfigModelType } from '../../discrete-layer/models';
import {
  UiDescriptorFieldType,
  UiDescriptorsTypeName,
  UiFieldDescriptor,
} from '../ui-descriptors/type';
import {
  ExternalLayerType,
  OptionsIssue,
  OptionsPolicy,
  getFullOptionsJsonSchema,
  getMandatoryKeys,
  getOptionsSchema,
  getModeKeys,
} from './external-layer-options';

/**
 * Bridge between the options schemas (Zod, from `@map-colonies/react-components/schemas`) and the entity descriptors
 * the app renders forms from (`LayersDetailsComponent`):
 *  - mandatory options become `UiDescriptors` fields, i.e. regular input components;
 *  - the remaining options are edited in `MonacoJSONEditor` with the `optional` schema mode.
 * The descriptors are derived from the schema, so a new mandatory option appears in the form without any hand-written field.
 */

type UiFieldType = Extract<UiDescriptorFieldType, 'string' | 'number'>;

/** A field of a `UiDescriptors` entity descriptor: field config of the model, marked as a UI descriptor. */
export type UiFieldConfig = Omit<Partial<FieldConfigModelType>, '__typename'> & UiFieldDescriptor;

interface JsonSchemaProperty {
  type?: string | string[];
  description?: string;
}

export type LabelResolver = (optionKey: string) => string;

/** i18n id of the label of an option; messages live under `basemaps.options.field.*`. */
export const defaultLabelResolver: LabelResolver = (key) => `basemaps.options.field.${key}`;

const toUiFieldType = (property: JsonSchemaProperty | undefined): UiFieldType | undefined => {
  const type = Array.isArray(property?.type) ? property?.type[0] : property?.type;
  switch (type) {
    case 'string':
      return 'string';
    case 'number':
    case 'integer':
      return 'number';
    default:
      // boolean/enum/object options are not part of the mandatory inputs so far: they stay in the JSON editor
      return undefined;
  }
};

const createUiField = (
  fieldName: string,
  uiDescriptorFieldType: UiFieldType,
  order: number,
  label: string
): UiFieldConfig => ({
  __typename: UiDescriptorsTypeName,
  uiDescriptorFieldType,
  uiShowError: true,
  uiAutoComplete: 'off',
  fieldName,
  label,
  order,
  queryableName: '',
  autocomplete: null,
  lookupTable: null,
  lookupExcludeFields: null,
  fullWidth: true,
  rows: null,
  infoMsgCode: null,
  isManuallyEditable: true,
  isSortable: null,
  isRequired: true,
  isAutoGenerated: null,
  isLifecycleEnvolved: null,
  isCopyable: null,
  isDisabled: null,
  isCreateEssential: null,
  isUpdateEssential: null,
  isMultiSelection: null,
  dateGranularity: null,
  shapeFileMapping: null,
  updateRules: null,
  enumValues: null,
  validation: null,
  isFilterable: null,
  isBriefField: null,
  isInfoTooltip: null,
  lookupTableBinding: null,
  dependentField: null,
  default: null,
});

/** Types of the mandatory options that have an input component, by option name. */
const getMandatoryFieldTypes = (
  type: ExternalLayerType,
  policy?: OptionsPolicy
): Array<[string, UiFieldType]> => {
  const properties = (getFullOptionsJsonSchema(type, policy).properties ?? {}) as Record<
    string,
    JsonSchemaProperty
  >;
  return getMandatoryKeys(type).flatMap((key) => {
    const uiType = toUiFieldType(properties[key]);
    return uiType ? [[key, uiType] as [string, UiFieldType]] : [];
  });
};

/** Entity descriptor (`UiDescriptors`) whose fields are the mandatory options of the link type. */
export const getMandatoryEntityDescriptors = (
  type: ExternalLayerType,
  policy?: OptionsPolicy,
  labelOf: LabelResolver = defaultLabelResolver
): EntityDescriptorModelType[] =>
  [
    {
      type: UiDescriptorsTypeName,
      categories: [
        {
          category: 'DUMMY',
          fields: getMandatoryFieldTypes(type, policy).map(([key, uiType], index) =>
            createUiField(key, uiType, index, labelOf(key))
          ),
        },
      ],
    },
  ] as unknown as EntityDescriptorModelType[];

/** Form values of the mandatory options, ready for formik (inputs are controlled, so no `undefined`). */
export const getMandatoryInitialValues = (
  type: ExternalLayerType,
  policy?: OptionsPolicy
): Record<string, string> =>
  Object.fromEntries(getMandatoryFieldTypes(type, policy).map(([key]) => [key, '']));

/** Form values -> options: empty inputs are dropped, numeric inputs converted. */
export const mandatoryValuesToOptions = (
  type: ExternalLayerType,
  values: Record<string, unknown>,
  policy?: OptionsPolicy
): Record<string, unknown> => {
  const options: Record<string, unknown> = {};
  getMandatoryFieldTypes(type, policy).forEach(([key, uiType]) => {
    const raw = values[key];
    if (raw === undefined || raw === null || String(raw).trim() === '') {
      return;
    }
    options[key] = uiType === 'number' ? Number(raw) : String(raw).trim();
  });
  return options;
};

export interface OptionsFormResult {
  /** Merged options (mandatory inputs + optional JSON); `undefined` while the JSON text is not an object. */
  options?: Record<string, unknown>;
  valid: boolean;
  /** Issues of mandatory inputs, by option name. */
  fieldIssues: Record<string, string>;
  /** Issues of the optional JSON editor (also unknown or misplaced keys). */
  editorIssues: OptionsIssue[];
}

/**
 * Validates both halves together against the full schema, so cross-field rules still apply,
 * and routes every issue to where the user can fix it: the input of a mandatory option or the JSON editor.
 */
export const validateOptionsForm = (
  type: ExternalLayerType,
  mandatoryValues: Record<string, unknown>,
  optionalText: string,
  policy?: OptionsPolicy
): OptionsFormResult => {
  let optional: unknown;
  try {
    optional = JSON.parse(optionalText.trim() === '' ? '{}' : optionalText);
  } catch (e) {
    return {
      valid: false,
      fieldIssues: {},
      editorIssues: [{ path: '', message: `Invalid JSON: ${(e as Error).message}` }],
    };
  }
  if (typeof optional !== 'object' || optional === null || Array.isArray(optional)) {
    return {
      valid: false,
      fieldIssues: {},
      editorIssues: [{ path: '', message: 'Expected a JSON object' }],
    };
  }

  const optionalKeys = new Set(getModeKeys(type, 'optional'));
  const misplaced = Object.keys(optional).filter((key) => !optionalKeys.has(key));
  const editorIssues: OptionsIssue[] = misplaced.map((key) => ({
    path: key,
    message: 'Option is not part of the optional options',
  }));

  const options = {
    ...(optional as Record<string, unknown>),
    ...mandatoryValuesToOptions(type, mandatoryValues, policy),
  };
  const result = getOptionsSchema(type, policy).safeParse(options);
  if (result.success) {
    return { options, valid: editorIssues.length === 0, fieldIssues: {}, editorIssues };
  }

  const mandatoryKeys = new Set(getMandatoryKeys(type));
  const fieldIssues: Record<string, string> = {};
  result.error.issues.forEach(({ path, message }) => {
    const key = String(path[0] ?? '');
    if (mandatoryKeys.has(key)) {
      fieldIssues[key] ??= message;
    } else if (!misplaced.includes(key)) {
      editorIssues.push({ path: path.join('.'), message });
    }
  });
  return { options, valid: false, fieldIssues, editorIssues };
};
